import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src", "opnsense", "scripts", "eero"))

FIXTURES = os.path.join(os.path.dirname(__file__), "fixtures")


def fixture(name):
    """The raw bytes of tests/fixtures/<name>.json."""
    with open(os.path.join(FIXTURES, name + ".json"), "rb") as f:
        return f.read()


def fixture_doc(name):
    return json.loads(fixture(name))
